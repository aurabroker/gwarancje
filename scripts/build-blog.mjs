/** Pełne escapowanie HTML — do tekstu i do wartości atrybutów (cudzysłowy podwójne). */
function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, (c) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
  })[c]);
}

/** Escapowanie dla XML (sitemap, RSS). */
const escapeXml = escapeHtml;

/** CDATA nie może zawierać "]]>" — rozbijamy sekwencję na dwie sekcje. */
function cdata(value) {
  return `<![CDATA[${String(value ?? '').replace(/\]\]>/g, ']]]]><![CDATA[>')}]]>`;
}

/**
 * JSON-LD osadzany w <script>: JSON.stringify + zamiana "<" na <,
 * żeby w treści nie dało się domknąć tagu </script>.
 */
function jsonLd(obj) {
  return JSON.stringify(obj, null, 2).replace(/</g, '\\u003c');
}

const POLISH_MAP = { ą: 'a', ć: 'c', ę: 'e', ł: 'l', ń: 'n', ó: 'o', ś: 's', ź: 'z', ż: 'z' };

/** Slug: małe litery a-z, cyfry i myślniki; polskie znaki transliterowane. */
function slugify(value) {
  return String(value ?? '')
    .toLowerCase()
    .replace(/[ąćęłńóśźż]/g, (c) => POLISH_MAP[c])
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/**
 * Tagi w bazie są zapisane niekonsekwentnie, np. ["#plynnoscfinansowa #gwarancjeubezpieczeniowe"]
 * jako jeden string. Normalizacja: rozbicie po białych znakach i przecinkach, zdjęcie "#",
 * usunięcie pustych i duplikatów (bez rozróżniania wielkości liter).
 */
function normaliseTags(raw) {
  let list = raw;
  if (typeof list === 'string') {
    const trimmed = list.trim();
    if (trimmed.startsWith('[')) {
      try {
        list = JSON.parse(trimmed);
      } catch {
        list = [trimmed];
      }
    } else {
      list = [trimmed];
    }
  }
  if (!Array.isArray(list)) list = list == null ? [] : [list];

  const seen = new Set();
  const out = [];
  for (const item of list) {
    for (const part of String(item ?? '').split(/[\s,]+/)) {
      const tag = part.replace(/^#+/, '').trim();
      if (!tag) continue;
      const key = tag.toLowerCase();
      const label = TAG_LABELS[key] || tag;
      const labelKey = label.toLowerCase();
      if (seen.has(key) || seen.has(labelKey)) continue;
      seen.add(key);
      seen.add(labelKey);
      out.push(label);
    }
  }
  return out;
}

/**
 * Prosty filtr treści artykułu (regex, bez parsera DOM). Treść pochodzi z własnego panelu
 * administracyjnego, więc to zabezpieczenie przed przypadkowo wklejonym skryptem, a nie pełny
 * sanitizer HTML. Usuwa:
 *   1. bloki <script>…</script>, także niedomknięte (<script … bez ">" połyka resztę strony),
 *   2. elementy, które nie mają prawa być w treści: <style>, <meta>, <base>, <link>, <object>,
 *      <embed>, <form>, <input>, <button>, <textarea>, <select>,
 *   3. <iframe> spoza listy (YouTube, YouTube nocookie, Vimeo),
 *   4. atrybuty zdarzeń on* — także bez spacji przed nazwą (<img src="x"onerror=…>, …/onerror=…),
 *   5. adresy javascript:/vbscript:/data:text w href/src/action/formaction/xlink:href, również
 *      zapisane z białymi znakami lub encjami (&#106;avascript:, java&#9;script:) → "#".
 * Reszta HTML (akapity, nagłówki, obrazy, linki, tabele, cytaty) zostaje bez zmian.
 */
const IFRAME_ALLOW = /^https:\/\/(www\.)?(youtube\.com|youtube-nocookie\.com|player\.vimeo\.com)\//i;

function decodeAttr(value) {
  return String(value ?? '')
    .replace(/&#x([0-9a-f]+);?/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);?/g, (_, d) => String.fromCodePoint(parseInt(d, 10)))
    .replace(/&colon;/gi, ':')
    .replace(/&tab;|&newline;/gi, '')
    .replace(/[\x00-\x20\x7f-\x9f\u200b-\u200f\u2028\u2029\ufeff]/g, '');
}

function unsafeUrl(value) {
  return /^(javascript|vbscript|data:text)/i.test(decodeAttr(value).replace(/^["']+/, ''));
}

function sanitiseContent(html) {
  let out = String(html ?? '');
  out = out.replace(/<script\b[^>]*>[\s\S]*?<\/script\s*>/gi, '');
  out = out.replace(/<script\b[^>]*$/gi, ''); // niedomknięty <script … na końcu
  out = out.replace(/<\/?script\b[^>]*>/gi, '');
  out = out.replace(/<style\b[^>]*>[\s\S]*?<\/style\s*>/gi, '');
  out = out.replace(/<\/?(meta|base|link|object|embed|form|input|button|textarea|select|style|applet)\b[^>]*>/gi, '');
  out = out.replace(/<iframe\b[^>]*>[\s\S]*?<\/iframe\s*>|<iframe\b[^>]*\/?>/gi, (tag) => {
    const m = tag.match(/\ssrc\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i);
    const src = m ? (m[1] ?? m[2] ?? m[3]) : '';
    return IFRAME_ALLOW.test(decodeAttr(src)) ? tag : '';
  });
  out = out.replace(/<[^>]+>/g, (tag) =>
    tag
      .replace(/(^|[\s"'\/])on[a-z]+\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+)/gi, '$1')
      .replace(
        /(\s)(href|src|action|formaction|xlink:href)\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/gi,
        (m, ws, name, v1, v2, v3) => (unsafeUrl(v1 ?? v2 ?? v3) ? `${ws}${name}="#"` : m),
      ),
  );
  return out.trim();
}

/**
 * Porządki redakcyjne po sanitizerze:
 *   1. akapity złożone wyłącznie z hashtagów (#wadium #nwk …) — zostają w bazie jako tagi social,
 *      ale na stronie są spamem i zawyżają wordCount,
 *   2. puste akapity <p></p> / <p><br></p>,
 *   3. brakujące atrybuty alt: pierwszy obraz dostaje tytuł artykułu, kolejne alt="" (dekoracyjne).
 */
function tidyContent(html, title) {
  let out = String(html ?? '');
  out = out.replace(/<p\b[^>]*>(?:\s|&nbsp;|<br\s*\/?>)*(?:#[^\s<#]+(?:\s|&nbsp;|<br\s*\/?>)*)+<\/p>/gi, '');
  out = out.replace(/<p\b[^>]*>(?:\s|&nbsp;|<br\s*\/?>)*<\/p>/gi, '');
  let first = true;
  out = out.replace(/<img\b[^>]*>/gi, (tag) => {
    const hasAlt = /\salt\s*=/i.test(tag);
    const alt = first ? escapeHtml(title) : '';
    first = false;
    if (hasAlt) return tag;
    return tag.replace(/\s*\/?>$/, (end) => ` alt="${alt}"${end.trim() === '/>' ? ' />' : '>'}`);
  });
  return out.trim();
}

/** Tekst bez tagów HTML (do opisu meta, liczenia słów). */
function textFromHtml(html) {
  return String(html ?? '')
    .replace(/<script\b[^>]*>[\s\S]*?<\/script\s*>/gi, ' ')
    .replace(/<style\b[^>]*>[\s\S]*?<\/style\s*>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&quot;/gi, '"')
    .replace(/&#0*39;|&#x27;|&apos;/gi, "'")
    .replace(/\s+/g, ' ')
    .trim();
}

/** Skraca tekst do max znaków, tnąc na granicy słowa i dodając wielokropek. */
function truncateAtWord(text, max) {
  const clean = String(text ?? '').replace(/\s+/g, ' ').trim();
  if (clean.length <= max) return clean;
  let cut = clean.slice(0, max);
  const lastSpace = cut.lastIndexOf(' ');
  if (lastSpace > max * 0.5) cut = cut.slice(0, lastSpace);
  return cut.replace(/[\s,;:.!?–-]+$/, '') + '…';
}

function wordCount(text) {
  const t = String(text ?? '').trim();
  return t ? t.split(/\s+/).length : 0;
}

function toDate(value) {
  if (!value) return null;
  const d = new Date(value);
  return Number.isNaN(d.getTime()) ? null : d;
}

