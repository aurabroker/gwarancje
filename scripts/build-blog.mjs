function tagChips(tags, size = 'md') {
  if (!tags.length) return '';
  const cls = size === 'sm' ? 'text-xs font-bold px-2 py-0.5 rounded-full' : 'text-xs font-bold px-3 py-1 rounded-full';
  return tags
    .map((t) => `<span class="${cls}" style="background:#cedcd8;color:#01696f">${escapeHtml(t)}</span>`)
    .join('\n');
}

