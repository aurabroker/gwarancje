// ───────────────────────────── sitemap i RSS ─────────────────────────────

async function renderSitemap(articles, buildDate) {
  const newest = articles.reduce(
    (max, a) => (a.published.getTime() > max.getTime() ? a.published : max),
    new Date(0),
  );
  const siteLastmod = isoDay(newest.getTime() > 0 ? newest : buildDate);

  const entries = [];
  entries.push(`  <url>
    <loc>${SITE_URL}/</loc>
    <lastmod>${siteLastmod}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>1.0</priority>
    <xhtml:link rel="alternate" hreflang="pl" href="${SITE_URL}/"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE_URL}/"/>
  </url>`);
  entries.push(`  <url>
    <loc>${BLOG_URL}</loc>
    <lastmod>${siteLastmod}</lastmod>
    <changefreq>weekly</changefreq>
    <priority>0.8</priority>
  </url>`);
  for (const a of articles) {
    entries.push(`  <url>
    <loc>${escapeXml(a.url)}</loc>
    <lastmod>${a.publishedDay}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.7</priority>
  </url>`);
  }
  for (const page of LEGAL_PAGES) {
    if (await exists(path.join(PUBLIC_DIR, page))) {
      entries.push(`  <url>
    <loc>${SITE_URL}/${page.replace(/\.html$/, '')}</loc>
    <changefreq>yearly</changefreq>
    <priority>0.3</priority>
  </url>`);
    }
  }

  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${entries.join('\n')}
</urlset>
`;
}

function renderFeed(articles, buildDate) {
  const newest = articles.length ? articles.reduce((m, a) => (a.published > m ? a.published : m), articles[0].published) : buildDate;
  const items = articles
    .map(
      (a) => `    <item>
      <title>${escapeXml(a.title)}</title>
      <link>${escapeXml(a.url)}</link>
      <guid isPermaLink="true">${escapeXml(a.url)}</guid>
      <pubDate>${rfc822(a.published)}</pubDate>
      <description>${cdata(a.excerpt || a.description)}</description>${
        a.tags.length ? '\n' + a.tags.map((t) => `      <category>${escapeXml(t)}</category>`).join('\n') : ''
      }
    </item>`,
    )
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${BLOG_TITLE}</title>
    <link>${BLOG_URL}</link>
    <description>${escapeXml(BLOG_DESCRIPTION)}</description>
    <language>pl</language>
    <lastBuildDate>${rfc822(newest)}</lastBuildDate>
    <atom:link href="${SITE_URL}/blog/feed.xml" rel="self" type="application/rss+xml"/>
${items}
  </channel>
</rss>
`;
}

// ───────────────────────────── główny przebieg ─────────────────────────────

async function main() {
  const buildDate = resolveBuildDate();
  const rows = await fetchArticles();
  const articles = prepareArticles(rows, buildDate);
  if (!articles.length) {
    const existing = (await exists(BLOG_DIR)) ? (await readdir(BLOG_DIR)).filter((n) => n.endsWith('.html')) : [];
    if (existing.length && process.env.ALLOW_EMPTY !== '1') {
      fail(
        `Supabase zwróciło 0 opublikowanych artykułów, a w public/blog/ są ${existing.length} wygenerowane strony. ` +
          'To zwykle oznacza zmianę RLS, nazwy platformy albo statusu, a nie świadome wycofanie bloga. ' +
          'Nic nie zmieniono. Jeśli pusty blog jest zamierzony, uruchom z ALLOW_EMPTY=1.',
      );
    }
    warn('Supabase zwróciło 0 opublikowanych artykułów — lista bloga będzie pusta.');
  }

  await mkdir(BLOG_DIR, { recursive: true });
  const generatedHtml = new Set();

  // 1. Strony artykułów
  for (const article of articles) {
    const others = articles.filter((o) => o.id !== article.id);
    await writeIfChanged(article.file, renderArticlePage(article, others));
    generatedHtml.add(path.basename(article.file));
  }

  // 2. /blog/index.json (stare linki blog.html#<uuid>). Dawny stub /blog/index.html nie jest
  //    już generowany — hosting serwuje blog.html pod /blog, a /blog/ przekierowuje na /blog;
  //    stary plik ma GENERATED_MARK, więc krok 6 go usunie.
  const idMap = Object.fromEntries(articles.map((a) => [a.id, a.slug]));
  await writeIfChanged(path.join(BLOG_DIR, 'index.json'), JSON.stringify(idMap, null, 2) + '\n');

  // 3. Lista artykułów w public/blog.html (tylko bloki między znacznikami)
  const blogFile = path.join(PUBLIC_DIR, 'blog.html');
  let blogHtml;
  try {
    blogHtml = await readFile(blogFile, 'utf8');
  } catch {
    fail(`brak pliku ${rel(blogFile)}.`);
  }
  const listInner = articles.length
    ? indentBlock(articles.map(renderCard).join('\n'), '          ')
    : '          <div class="col-span-full py-20 text-center text-slate-400 font-medium">Brak opublikowanych artykułów.</div>';
  let updated = replaceBetween(blogHtml, MARK_LIST_START, MARK_LIST_END, listInner);
  if (updated === null) fail(`w ${rel(blogFile)} brakuje znaczników ${MARK_LIST_START} / ${MARK_LIST_END}.`);
  const schemaInner = `  <script type="application/ld+json">\n${blogListJsonLd(articles)}\n  </script>`;
  const updated2 = replaceBetween(updated, MARK_SCHEMA_START, MARK_SCHEMA_END, schemaInner);
  if (updated2 === null) fail(`w ${rel(blogFile)} brakuje znaczników ${MARK_SCHEMA_START} / ${MARK_SCHEMA_END}.`);
  await writeIfChanged(blogFile, updated2);

  // 4. Karta "Aktualności" w hero strony głównej (tylko jeśli są znaczniki)
  const indexFile = path.join(PUBLIC_DIR, 'index.html');
  if (await exists(indexFile)) {
    const indexHtml = await readFile(indexFile, 'utf8');
    const heroUpdated = replaceBetween(indexHtml, MARK_HERO_START, MARK_HERO_END, indentBlock(renderHeroPosts(articles), '        '));
    if (heroUpdated === null) {
      warn(`w ${rel(indexFile)} brak znaczników ${MARK_HERO_START} / ${MARK_HERO_END} — karta hero pominięta.`);
    } else {
      await writeIfChanged(indexFile, heroUpdated);
    }
  } else {
    warn(`brak pliku ${rel(indexFile)} — karta hero pominięta.`);
  }

  // 5. Sitemap i RSS
  await writeIfChanged(path.join(PUBLIC_DIR, 'sitemap.xml'), await renderSitemap(articles, buildDate));
  await writeIfChanged(path.join(BLOG_DIR, 'feed.xml'), renderFeed(articles, buildDate));

  // 6. Usunięcie nieaktualnych stron (tylko plików z GENERATED_MARK)
  for (const name of await readdir(BLOG_DIR)) {
    if (!name.endsWith('.html') || generatedHtml.has(name)) continue;
    const file = path.join(BLOG_DIR, name);
    let content = '';
    try {
      content = await readFile(file, 'utf8');
    } catch {
      continue;
    }
    if (content.includes(GENERATED_MARK)) {
      await unlink(file);
      stats.removed.push(rel(file));
    }
  }

  // 7. Podsumowanie
  console.log(
    `[build-blog] ${articles.length} artykuł(ów) · zapisano ${stats.written.length} · bez zmian ${stats.unchanged.length} · usunięto ${stats.removed.length} · data: ${isoDay(buildDate)}`,
  );
  for (const f of stats.written) console.log(`  zapisano   ${f}`);
  for (const f of stats.removed) console.log(`  usunięto   ${f}`);
  if (stats.warnings.length) console.log(`  ostrzeżeń: ${stats.warnings.length}`);
}

