function resolveBuildDate() {
  const env = process.env.BUILD_DATE;
  if (!env) return new Date();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(env) || !toDate(`${env}T00:00:00Z`)) {
    fail(`BUILD_DATE musi mieć format YYYY-MM-DD (otrzymano "${env}").`);
  }
  return new Date(`${env}T00:00:00Z`);
}

async function writeIfChanged(file, content) {
  let current = null;
  try {
    current = await readFile(file, 'utf8');
  } catch {
    /* plik nie istnieje */
  }
  if (current === content) {
    stats.unchanged.push(rel(file));
    return false;
  }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, content, 'utf8');
  stats.written.push(rel(file));
  return true;
}

/**
 * Podmienia blok między znacznikami (włącznie z białymi znakami przed znacznikiem końcowym),
 * zachowując wcięcie znacznika początkowego. Zwraca null, gdy znaczników brak.
 */
function replaceBetween(source, startMark, endMark, inner) {
  const start = source.indexOf(startMark);
  const end = source.indexOf(endMark, start + startMark.length);
  if (start === -1 || end === -1) return null;
  const lineStart = source.lastIndexOf('\n', start) + 1;
  const indent = source.slice(lineStart, start).match(/^[ \t]*/)[0];
  const body = inner ? `\n${inner}\n${indent}` : `\n${indent}`;
  return source.slice(0, start + startMark.length) + body + source.slice(end);
}

function indentBlock(text, indent) {
  return text
    .split('\n')
    .map((line) => (line ? indent + line : line))
    .join('\n');
}

